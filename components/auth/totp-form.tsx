"use client";

import { useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { Button } from "@/components/ui/primitives";
import { authInput } from "./auth-frame";

export type MfaState =
  | { mode: "verify"; factorId: string }
  | { mode: "enroll"; factorId: string; qrCode: string; secret: string };
type VerifyResult = { ok: true; redirectTo: string } | { ok: false; error: string };

/** Authenticator step, shared by platform admins (L1) and clinic admins/doctors (P-11). */
export function TotpForm({
  state, verify, signOut,
}: {
  state: MfaState;
  verify: (input: { factorId: string; code: string; enrolling: boolean }) => Promise<VerifyResult>;
  signOut: () => Promise<void>;
}) {
  const router = useRouter();
  const [pending, start] = useTransition();
  const [error, setError] = useState<string | null>(null);
  const [showSecret, setShowSecret] = useState(false);
  const enrolling = state.mode === "enroll";

  function onSubmit(e: React.FormEvent<HTMLFormElement>) {
    e.preventDefault();
    const code = String(new FormData(e.currentTarget).get("code") ?? "");
    setError(null);
    start(async () => {
      const res = await verify({ factorId: state.factorId, code, enrolling });
      if (res.ok) {
        router.replace(res.redirectTo);
        router.refresh();
      } else {
        setError(res.error);
      }
    });
  }

  return (
    <div className="space-y-5">
      {state.mode === "enroll" ? (
        <div className="space-y-3">
          <p className="font-medium">Set up your authenticator</p>
          <p className="text-sm text-ink-soft">
            Platform accounts need a second step. Scan this code with an authenticator app
            (Google Authenticator, Microsoft Authenticator, 1Password…), then enter the 6-digit code it shows.
          </p>
          <div className="flex justify-center rounded-control border border-line bg-white p-3">
            {/* The QR is an SVG data URL generated by Supabase Auth for this account only. */}
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={state.qrCode} alt="QR code for your authenticator app" width={184} height={184} />
          </div>
          <button type="button" onClick={() => setShowSecret((s) => !s)} className="text-sm text-pine hover:underline">
            {showSecret ? "Hide setup key" : "Can't scan? Show the setup key"}
          </button>
          {showSecret ? <p className="break-all rounded-control bg-sunken px-3 py-2 font-medium tracking-wide">{state.secret}</p> : null}
        </div>
      ) : (
        <p className="text-ink-soft">Enter the 6-digit code from your authenticator app.</p>
      )}

      <form onSubmit={onSubmit} className="space-y-4">
        <label className="block">
          <span className="mb-1 block text-sm font-medium">Code</span>
          <input name="code" inputMode="numeric" autoComplete="one-time-code" pattern="\d{6}" maxLength={6} required autoFocus
            className={`${authInput} text-center text-2xl tracking-[0.4em]`} />
        </label>
        {error ? <p role="alert" className="rounded-control bg-alert-tint px-3 py-2 text-sm text-alert">{error}</p> : null}
        <Button type="submit" className="w-full" disabled={pending}>{pending ? "Checking…" : enrolling ? "Turn on and sign in" : "Sign in"}</Button>
      </form>

      <form action={signOut}>
        <button type="submit" className="text-sm text-ink-faint hover:text-ink">Use a different account</button>
      </form>
    </div>
  );
}

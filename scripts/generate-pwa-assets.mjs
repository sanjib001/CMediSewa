// Generates the installed app's launch images (owner: "logo while loading, same as HRestroSewa").
//
// iOS shows a launch image only when a <link rel="apple-touch-startup-image"> matches the device
// EXACTLY (width, height, pixel ratio, orientation); anything unmatched opens on a blank screen.
// So: one image per device and orientation, the mark and the name centred on the app's own
// background (no white→canvas flash). Android needs no images: Chrome builds its launch screen
// from the manifest's background_color and icon.
//
// One-shot, not part of the build; the PNGs and lib/pwa/apple-splash.ts are committed.
// Re-run only when the mark or the device list changes:
//
//     node scripts/generate-pwa-assets.mjs
//
// sharp comes with Next (next/image), so there is no new dependency.
import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { markSvg, CANVAS, INK } from "../lib/pwa/mark.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const sharp = createRequire(join(ROOT, "package.json"))("sharp");
const PUBLIC = join(ROOT, "public");

// The same device table as HRestroSewa (iPhone SE → 16 Pro Max, iPads).
const DEVICES = [
  { w: 430, h: 932, dpr: 3 }, { w: 393, h: 852, dpr: 3 }, { w: 428, h: 926, dpr: 3 }, { w: 390, h: 844, dpr: 3 },
  { w: 375, h: 812, dpr: 3 }, { w: 414, h: 896, dpr: 3 }, { w: 414, h: 896, dpr: 2 }, { w: 414, h: 736, dpr: 3 },
  { w: 375, h: 667, dpr: 2 }, { w: 1024, h: 1366, dpr: 2 }, { w: 834, h: 1194, dpr: 2 }, { w: 834, h: 1112, dpr: 2 },
  { w: 820, h: 1180, dpr: 2 }, { w: 768, h: 1024, dpr: 2 },
];

// The mark: a fixed share of the SHORT edge, so it's the same size on a phone and an iPad; the
// name sits under it.
async function splash(pxW, pxH, file) {
  const short = Math.min(pxW, pxH);
  const mark = Math.round(short * 0.26);
  const font = Math.round(short * 0.062);
  const gap = Math.round(short * 0.05);
  const blockH = mark + gap + font;
  const top = Math.round((pxH - blockH) / 2);
  const name = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${pxW}" height="${font * 2}">
    <text x="50%" y="${font}" text-anchor="middle" dominant-baseline="central" font-family="Mukta, 'Segoe UI', Arial, sans-serif"
      font-size="${font}" font-weight="600" fill="${INK}">CMediSewa</text></svg>`);
  await sharp({ create: { width: pxW, height: pxH, channels: 4, background: CANVAS } })
    .composite([
      { input: Buffer.from(markSvg(mark)), top, left: Math.round((pxW - mark) / 2) },
      { input: name, top: top + mark + gap - Math.round(font / 2), left: 0 },
    ])
    .png({ compressionLevel: 9 })
    .toFile(join(PUBLIC, file));
}

await mkdir(join(PUBLIC, "splash"), { recursive: true });
const entries = [];
for (const d of DEVICES) {
  const pw = d.w * d.dpr, ph = d.h * d.dpr;
  for (const [o, W, H] of [["portrait", pw, ph], ["landscape", ph, pw]]) {
    const file = `splash/${d.w}x${d.h}@${d.dpr}x-${o}.png`;
    await splash(W, H, file);
    entries.push({ href: `/${file}`, media: `(device-width: ${d.w}px) and (device-height: ${d.h}px) and (-webkit-device-pixel-ratio: ${d.dpr}) and (orientation: ${o})` });
  }
}
await writeFile(join(ROOT, "lib/pwa/apple-splash.ts"),
  `// GENERATED by scripts/generate-pwa-assets.mjs; do not edit by hand.\n`
  + `// iOS matches a launch image on an exact device-width/height/DPR/orientation query.\n`
  + `export const APPLE_SPLASH: { url: string; media: string }[] = ${JSON.stringify(entries.map((e) => ({ url: e.href, media: e.media })), null, 2)};\n`);
console.log(`wrote ${entries.length} launch images and lib/pwa/apple-splash.ts`);

#!/usr/bin/env node
/**
 * Generates supabase/migrations/20261120100300_fiscal_calendar.sql.
 *
 * Nepal's fiscal year runs from 1 Shrawan (BS month 4) to the end of Asar. Its AD start
 * date moves by a day between years, so it cannot be computed with a fixed rule; it comes
 * from Bikram Sambat calendar data. Two independent libraries are compared and the script
 * REFUSES to write if they disagree on any year (nepali-date-converter is the runtime
 * library, bikram-sambat the cross-check).
 *
 * Both libraries end at 2090 BS, so the seeded range is FY 2070/71 … 2089/90
 * (AD 2013-07 … 2033-07). Extend with a NEW migration before 2032 (roadmap risk).
 *
 *   node scripts/gen-fiscal-calendar.mjs           (re-run only to regenerate identical SQL)
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { ROOT } from "./lib/db.mjs";

const require = createRequire(import.meta.url);
const ndcMod = require("nepali-date-converter");
const NepaliDate = ndcMod.default ?? ndcMod;
const bs = require("bikram-sambat");

const FIRST = 2070, LAST_START = 2090; // FY codes FIRST/FIRST+1 … (LAST_START-1)/LAST_START
const iso = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
const pad = (n) => String(n).padStart(2, "0");

const starts = [];
for (let y = FIRST; y <= LAST_START; y++) {
  const a = iso(new NepaliDate(y, 3, 1).toJsDate()); // month index 3 = Shrawan
  const g = bs.toGreg(y, 4, 1);
  const b = `${g.year}-${pad(g.month)}-${pad(g.day)}`;
  if (a !== b) throw new Error(`libraries disagree on 1 Shrawan ${y}: ${a} vs ${b}`);
  starts.push({ y, start: a });
}

const rows = [];
for (let i = 0; i < starts.length - 1; i++) {
  const { y, start } = starts[i];
  const nextStart = new Date(`${starts[i + 1].start}T00:00:00Z`);
  nextStart.setUTCDate(nextStart.getUTCDate() - 1);
  const end = nextStart.toISOString().slice(0, 10);
  const code = `${y}/${String((y + 1) % 100).padStart(2, "0")}`;
  rows.push(`  ('${code}', ${y}, date '${start}', date '${end}')`);
}

const sql = `-- =============================================================================
-- 0004 FISCAL CALENDAR (GENERATED by scripts/gen-fiscal-calendar.mjs; do not hand-edit)
--
-- Nepali fiscal years (1 Shrawan → end of Asar) as AD date ranges, cross-checked between
-- two independent BS calendar libraries. Used by document numbering (series reset per
-- fiscal year, D-22/D-49) and fiscal reports. Range: FY ${rows.length ? `${FIRST}/${String((FIRST + 1) % 100).padStart(2, "0")}` : ""} … ${LAST_START - 1}/${String(LAST_START % 100).padStart(2, "0")}.
-- fiscal_year_of() raises FISCAL_YEAR_UNKNOWN outside the range rather than guessing.
-- =============================================================================

create table fiscal_years (
  code           text primary key check (code ~ '^[0-9]{4}/[0-9]{2}$'),
  bs_start_year  smallint not null unique,
  starts_on      date not null unique,
  ends_on        date not null,
  check (ends_on > starts_on)
);
comment on table fiscal_years is
  'Platform reference data: Nepali fiscal years as AD ranges. Not tenant-owned. Generated, cross-validated against two BS libraries.';

insert into fiscal_years (code, bs_start_year, starts_on, ends_on) values
${rows.join(",\n")};

alter table fiscal_years enable row level security;
revoke insert, update, delete on fiscal_years from service_role;

-- The fiscal year a moment belongs to, judged by the LOCAL calendar date in the given
-- timezone (a bill at 00:30 on 1 Shrawan in Kathmandu is in the new year, even though it
-- is still the previous day in UTC).
create or replace function fiscal_year_of(p_at timestamptz, p_tz text default 'Asia/Kathmandu')
returns text
language plpgsql
stable
set search_path = pg_catalog, public
as $$
declare
  v_day  date := (p_at at time zone p_tz)::date;
  v_code text;
begin
  select code into v_code from fiscal_years where v_day between starts_on and ends_on;
  if v_code is null then
    raise exception 'FISCAL_YEAR_UNKNOWN: % is outside the seeded fiscal calendar', v_day using errcode = 'P0001';
  end if;
  return v_code;
end;
$$;
comment on function fiscal_year_of(timestamptz, text) is
  'Nepali fiscal year code (e.g. 2082/83) of a moment, by local date in p_tz. Raises outside the seeded range.';

revoke all on function fiscal_year_of(timestamptz, text) from public, anon, authenticated;
grant execute on function fiscal_year_of(timestamptz, text) to service_role;
`;

const out = path.join(ROOT, "supabase", "migrations", "20261120100300_fiscal_calendar.sql");
fs.writeFileSync(out, sql);
console.log(`wrote ${path.relative(ROOT, out)}: ${rows.length} fiscal years, libraries agree on all ${starts.length} start dates`);
